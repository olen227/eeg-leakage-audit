        with open(path, encoding="utf-8") as f:
            src = f.read().splitlines()
        A(f"## {num}. `{rel}`")
        A("")
        A(f"**Назначение.** {hdr}")
        A("")
        A(f"**Путь:** `{path}`  ")
        A(f"**Строк:** {len(src)}  ")
        A(f"**SHA-256:** `{sha(path)}`")
        A("")
